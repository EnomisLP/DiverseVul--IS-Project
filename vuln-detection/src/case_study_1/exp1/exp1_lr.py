@dataclass(frozen=True)
class Exp1Config:
    """Declared reproducible configuration for CS1-EXP1-LR, including every searched grid."""

    experiment_name: str = "cs1_exp1_lr"
    code_column: str = "normalized_code"
    source_id_column: str = "source_row_id"
    label_column: str = "label"
    project_column: str = "project"
    fold_column: str = "fold"

    n_splits: int = 5
    random_state: int = 42

    # Word TF-IDF: identifiers, API calls, and local lexical sequences.
    word_ngram_range: tuple[int, int] = (1, 3)
    word_max_df: float = 0.995
    word_max_features_grid: tuple[int, ...] = (20_000, 50_000, 80_000)
    word_min_df_grid: tuple[int, ...] = (2, 3)

    # Character TF-IDF: punctuation, pointer/array patterns, and partial tokens.
    char_analyzer: str = "char"
    char_ngram_range: tuple[int, int] = (3, 4)
    char_max_df: float = 0.995
    char_max_features_grid: tuple[int, ...] = (30_000, 60_000, 90_000)
    char_min_df_grid: tuple[int, ...] = (5, 8)

    lowercase: bool = False
    sublinear_tf: bool = True
    tfidf_norm: str = "l2"

    # SGD-based binary Logistic Regression: scalable for sparse TF-IDF.
    sgd_loss: str = "log_loss"
    sgd_penalty: str = "l2"
    sgd_alpha_grid: tuple[float, ...] = (1e-6, 3e-6, 1e-5, 3e-5, 1e-4)
    sgd_class_weight: str = "balanced"
    sgd_max_iter: int = 80
    sgd_tol: float = 1e-3
    sgd_average: bool = True

    # Inner CV used to select every grid above, per outer fold.
    inner_n_splits: int = 3
    inner_random_state: int = 20260707
    selection_metric: str = "average_precision_pr_auc"

    top_features_per_direction: int = 30
    verbose: bool = True



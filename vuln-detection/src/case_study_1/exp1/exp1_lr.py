"""
CS1-EXP1: word + character TF-IDF with class-weighted SGD Logistic Regression.

    normalized C/C++ function text
        -> word TF-IDF, n-grams (1, 3)
        +  character TF-IDF, n-grams (3, 4)
        -> sparse feature union
        -> class-weighted L2 Logistic Regression trained with SGD

Evaluation protocol
--------------------
5-fold project-grouped, stratified CV; every fold takes a turn as the test
set (no separate fixed holdout). For each outer fold, TF-IDF capacity
(word/char max_features, word/char min_df), the SGD L2 penalty (alpha), and
the decision threshold are all selected via 3-fold inner CV on that outer
fold's training projects only, then the winning configuration is refit on
the full outer-training partition and scored once on the untouched outer
test fold. Reported metrics are mean +/- std across the 5 outer folds.
"""


@dataclass(frozen=True)
class Exp1Config:
    """Declared reproducible configuration for CS1-EXP1-RF."""

    experiment_name: str = "cs1_exp1_rf"
    code_column: str = "normalized_code"
    source_id_column: str = "source_row_id"
    label_column: str = "label"
    project_column: str = "project"
    fold_column: str = "fold"

    n_splits: int = 5
    random_state: int = 42
    decision_threshold: float = 0.50

    # Same lexical source representation used by EXP-0.
    word_ngram_range: tuple[int, int] = (1, 3)
    word_min_df: int = 3
    word_max_df: float = 0.995
    word_max_features: int = 50_000

    char_analyzer: str = "char"
    char_ngram_range: tuple[int, int] = (3, 4)
    char_min_df: int = 8
    char_max_df: float = 0.995
    char_max_features: int = 60_000

    lowercase: bool = False
    sublinear_tf: bool = True
    tfidf_norm: str = "l2"

    # Fit only within each training fold. 256 lexical dimensions + 54 static
    # features means each forest sees 310 dense input dimensions.
    svd_n_components: int = 256
    svd_algorithm: str = "randomized"
    svd_n_iter: int = 5
    svd_n_oversamples: int = 10

    # Random Forest configuration.
    # Profile-driven compute budget, fixed before the official run.
    rf_n_estimators: int = 200
    rf_criterion: str = "gini"
    rf_max_depth: Optional[int] = None
    rf_min_samples_split: int = 2
    rf_min_samples_leaf: int = 2
    rf_max_features: str = "sqrt"
    rf_bootstrap: bool = True
    rf_max_samples: Optional[float] = 0.70
    rf_class_weight: str = "balanced_subsample"
    rf_n_jobs: int = -1
    rf_oob_score: bool = True

    # Threshold is selected only from OOB predictions of each outer-fold
    # training partition. The held-out project data never participates.
    oob_threshold_min: float = 0.005
    oob_threshold_max: float = 0.250
    oob_threshold_step: float = 0.005
    oob_threshold_objective: str = "f1"

    feature_importance_top_n: int = 50
    verbose: bool = True



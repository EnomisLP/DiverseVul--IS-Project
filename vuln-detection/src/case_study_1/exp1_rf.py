"""
CS1-EXP1-RF: TF-IDF + TruncatedSVD + deterministic static features + Random Forest.

Pipeline per outer fold
-----------------------
1. Fit word and character TF-IDF only on training code.
2. Join sparse lexical matrices.
3. Fit TruncatedSVD only on the training sparse lexical matrix.
4. Join dense SVD vectors with cached deterministic static code features.
5. Fit a class-weighted Random Forest.
6. Score the held-out projects and collect pooled OOF predictions.

Leakage controls
----------------
- The fixed 5-fold project-aware manifest is reused unchanged.
- Word TF-IDF, character TF-IDF, and TruncatedSVD are fitted inside each
  training fold only.
- Static features are deterministic functions of each function's own source
  code. They are cached globally for efficiency but contain no labels,
  corpus-level IDF values, scaling statistics, or learned parameters.

Interpretation
--------------
- Random Forest probability scores are ranking scores for this benchmark.
  They should not be presented as calibrated real-world vulnerability
  probabilities.
- SVD components are latent lexical dimensions, not directly interpretable
  code concepts.
- Random Forest impurity importances are descriptive diagnostics only.
"""


def _log(message: str, enabled: bool = True) -> None:
    if enabled:
        timestamp = datetime.now().strftime("%H:%M:%S")
        print(f"[{timestamp}] {message}", flush=True)


def _format_seconds(seconds: float) -> str:
    seconds = float(seconds)
    return f"{seconds:.1f}s" if seconds < 60 else f"{seconds / 60:.2f} min"


def _require_columns(frame: pd.DataFrame, columns: Sequence[str]) -> None:
    missing = [column for column in columns if column not in frame.columns]
    if missing:
        raise KeyError(
            f"Missing required column(s): {missing}. "
            f"Available columns: {sorted(frame.columns.tolist())}"
        )


def _validate_config(config: Exp1Config) -> None:
    if config.n_splits < 2:
        raise ValueError("n_splits must be >= 2.")
    if not 0.0 < float(config.decision_threshold) < 1.0:
        raise ValueError("decision_threshold must lie strictly between 0 and 1.")
    if config.word_min_df < 1 or config.char_min_df < 1:
        raise ValueError("word_min_df and char_min_df must be >= 1.")
    if config.word_max_features < 1 or config.char_max_features < 1:
        raise ValueError("word_max_features and char_max_features must be >= 1.")
    if config.svd_n_components < 2:
        raise ValueError("svd_n_components must be >= 2.")
    if config.svd_algorithm != "randomized":
        raise ValueError(
            "This EXP-1 implementation is declared for randomized TruncatedSVD."
        )
    if config.svd_n_iter < 1 or config.svd_n_oversamples < 1:
        raise ValueError("SVD iteration and oversampling values must be >= 1.")
    if config.rf_n_estimators < 1:
        raise ValueError("rf_n_estimators must be >= 1.")
    if config.rf_min_samples_split < 2:
        raise ValueError("rf_min_samples_split must be >= 2.")
    if config.rf_min_samples_leaf < 1:
        raise ValueError("rf_min_samples_leaf must be >= 1.")
    if config.rf_class_weight not in {"balanced", "balanced_subsample"}:
        raise ValueError(
            "rf_class_weight must be 'balanced' or 'balanced_subsample'."
        )
    if config.rf_max_samples is not None:
        if not config.rf_bootstrap:
            raise ValueError("rf_max_samples requires rf_bootstrap=True.")
        if not 0.0 < float(config.rf_max_samples) <= 1.0:
            raise ValueError("rf_max_samples must be in (0, 1] when provided.")
    if not config.rf_oob_score:
        raise ValueError(
            "EXP-1 v2 requires rf_oob_score=True for training-only threshold selection."
        )
    if not (0.0 < config.oob_threshold_min < config.oob_threshold_max < 1.0):
        raise ValueError("Invalid OOB threshold range.")
    if config.oob_threshold_step <= 0.0:
        raise ValueError("oob_threshold_step must be positive.")
    if config.oob_threshold_objective != "f1":
        raise ValueError("This implementation currently supports oob_threshold_objective='f1'.")


def _validate_dataset_with_folds(
    frame: pd.DataFrame,
    config: Exp1Config,
) -> pd.DataFrame:
    _require_columns(
        frame,
        [
            config.source_id_column,
            config.code_column,
            config.label_column,
            config.project_column,
            config.fold_column,
        ],
    )

    checked = frame.copy()
    if checked[config.source_id_column].isna().any():
        raise ValueError("source_row_id contains missing values.")
    if checked[config.source_id_column].duplicated().any():
        raise ValueError("source_row_id contains duplicate values.")

    checked[config.code_column] = checked[config.code_column].fillna("").astype(str)
    if (checked[config.code_column].str.strip() == "").any():
        raise ValueError(
            "EXP-1 received empty normalized_code rows. "
            "Use the normalized dataset that passed EXP-0 integrity checks."
        )

    labels = pd.to_numeric(checked[config.label_column], errors="raise")
    if not labels.isin([0, 1]).all():
        raise ValueError("label must contain only 0 and 1.")
    checked[config.label_column] = labels.astype("int8")

    checked[config.project_column] = (
        checked[config.project_column].fillna("").astype(str).str.strip()
    )
    if (checked[config.project_column] == "").any():
        raise ValueError("project contains missing or empty identifiers.")

    folds = pd.to_numeric(checked[config.fold_column], errors="raise").astype(int)
    expected = set(range(config.n_splits))
    if set(folds.unique().tolist()) != expected:
        raise ValueError(
            f"Expected folds {sorted(expected)}; "
            f"observed {sorted(folds.unique().tolist())}."
        )
    checked[config.fold_column] = folds.astype("int8")
    return checked


def _validate_static_feature_frame(
    static_features_frame: pd.DataFrame,
    config: Exp1Config,
) -> pd.DataFrame:
    required = [config.source_id_column] + FEATURE_COLUMNS
    _require_columns(static_features_frame, required)

    static_checked = static_features_frame[required].copy()
    if static_checked[config.source_id_column].isna().any():
        raise ValueError("Static feature cache has missing source_row_id values.")
    if static_checked[config.source_id_column].duplicated().any():
        raise ValueError("Static feature cache has duplicate source_row_id values.")

    for column in FEATURE_COLUMNS:
        static_checked[column] = pd.to_numeric(
            static_checked[column],
            errors="raise",
        ).astype(np.float32)

    values = static_checked[FEATURE_COLUMNS].to_numpy(dtype=np.float32)
    if not np.isfinite(values).all():
        raise ValueError("Static feature cache contains NaN or infinite values.")
    if (values < 0).any():
        raise ValueError("Static feature cache contains negative count/proxy values.")

    return static_checked.set_index(config.source_id_column, drop=True)


def _prepare_dataset_and_static_lookup(
    normalized_frame: pd.DataFrame,
    static_features_frame: pd.DataFrame,
    manifest: pd.DataFrame,
    config: Exp1Config,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Attach the frozen manifest and validate the aligned static feature cache."""
    assert_manifest_integrity(
        manifest,
        config=SplitConfig(
            n_splits=config.n_splits,
            random_state=config.random_state,
            source_id_column=config.source_id_column,
            label_column=config.label_column,
            group_column=config.project_column,
        ),
    )

    dataset = apply_manifest(
        normalized_frame,
        manifest,
        source_id_column=config.source_id_column,
    )
    dataset = _validate_dataset_with_folds(dataset, config)

    static_lookup = _validate_static_feature_frame(static_features_frame, config)

    dataset_ids = pd.Index(dataset[config.source_id_column])
    static_ids = static_lookup.index

    missing_static = dataset_ids.difference(static_ids)
    unexpected_static = static_ids.difference(dataset_ids)

    if len(missing_static) or len(unexpected_static):
        raise ValueError(
            "Static feature cache IDs do not exactly match the normalized dataset. "
            f"missing={len(missing_static):,}, unexpected={len(unexpected_static):,}."
        )

    for fold_id in range(config.n_splits):
        held_out_projects = set(
            dataset.loc[
                dataset[config.fold_column] == fold_id,
                config.project_column,
            ]
        )
        train_projects = set(
            dataset.loc[
                dataset[config.fold_column] != fold_id,
                config.project_column,
            ]
        )
        overlap = held_out_projects.intersection(train_projects)
        if overlap:
            raise RuntimeError(
                f"Project leakage detected in fold {fold_id}; "
                f"examples: {sorted(overlap)[:10]}"
            )

    return dataset, static_lookup


def _build_word_vectorizer(config: Exp1Config) -> TfidfVectorizer:
    return TfidfVectorizer(
        analyzer="word",
        token_pattern=r"(?u)\b\w+\b",
        ngram_range=config.word_ngram_range,
        min_df=config.word_min_df,
        max_df=config.word_max_df,
        max_features=config.word_max_features,
        lowercase=config.lowercase,
        sublinear_tf=config.sublinear_tf,
        norm=config.tfidf_norm,
        dtype=np.float32,
    )


def _build_char_vectorizer(config: Exp1Config) -> TfidfVectorizer:
    return TfidfVectorizer(
        analyzer=config.char_analyzer,
        ngram_range=config.char_ngram_range,
        min_df=config.char_min_df,
        max_df=config.char_max_df,
        max_features=config.char_max_features,
        lowercase=config.lowercase,
        sublinear_tf=config.sublinear_tf,
        norm=config.tfidf_norm,
        dtype=np.float32,
    )


def _fit_lexical_matrices(
    train_code: pd.Series,
    test_code: pd.Series,
    config: Exp1Config,
    fold_id: int,
):
    """Fit train-only TF-IDF matrices and return joined sparse lexical features."""
    label = f"Fold {fold_id + 1}/{config.n_splits}"

    word_vectorizer = _build_word_vectorizer(config)
    char_vectorizer = _build_char_vectorizer(config)

    _log(f"{label} | fitting word TF-IDF...", config.verbose)
    start = time.perf_counter()
    x_train_word = word_vectorizer.fit_transform(train_code)
    x_test_word = word_vectorizer.transform(test_code)
    word_seconds = float(time.perf_counter() - start)
    _log(
        f"{label} | word TF-IDF done in {_format_seconds(word_seconds)} "
        f"({x_train_word.shape[1]:,} features).",
        config.verbose,
    )

    _log(f"{label} | fitting character TF-IDF...", config.verbose)
    start = time.perf_counter()
    x_train_char = char_vectorizer.fit_transform(train_code)
    x_test_char = char_vectorizer.transform(test_code)
    char_seconds = float(time.perf_counter() - start)
    _log(
        f"{label} | character TF-IDF done in {_format_seconds(char_seconds)} "
        f"({x_train_char.shape[1]:,} features).",
        config.verbose,
    )

    _log(f"{label} | joining sparse lexical matrices...", config.verbose)
    start = time.perf_counter()
    x_train_lexical = hstack(
        [x_train_word, x_train_char],
        format="csr",
        dtype=np.float32,
    )
    x_test_lexical = hstack(
        [x_test_word, x_test_char],
        format="csr",
        dtype=np.float32,
    )
    sparse_join_seconds = float(time.perf_counter() - start)

    metadata = {
        "word_features": int(x_train_word.shape[1]),
        "char_features": int(x_train_char.shape[1]),
        "lexical_features": int(x_train_lexical.shape[1]),
        "word_tfidf_seconds": word_seconds,
        "char_tfidf_seconds": char_seconds,
        "sparse_join_seconds": sparse_join_seconds,
        "vectorization_seconds": float(
            word_seconds + char_seconds + sparse_join_seconds
        ),
    }

    _log(
        f"{label} | sparse lexical matrix ready in "
        f"{_format_seconds(sparse_join_seconds)} "
        f"({metadata['lexical_features']:,} columns).",
        config.verbose,
    )

    return x_train_lexical, x_test_lexical, metadata


def _fit_and_transform_svd(
    x_train_lexical,
    x_test_lexical,
    config: Exp1Config,
    fold_id: int,
) -> tuple[np.ndarray, np.ndarray, float, float]:
    """Fit train-only TruncatedSVD and transform train/test lexical features."""
    if config.svd_n_components >= x_train_lexical.shape[1]:
        raise ValueError(
            "svd_n_components must be lower than lexical feature count; "
            f"received {config.svd_n_components} for "
            f"{x_train_lexical.shape[1]} lexical features."
        )

    label = f"Fold {fold_id + 1}/{config.n_splits}"
    svd = TruncatedSVD(
        n_components=config.svd_n_components,
        algorithm=config.svd_algorithm,
        n_iter=config.svd_n_iter,
        n_oversamples=config.svd_n_oversamples,
        random_state=config.random_state,
    )

    _log(
        f"{label} | fitting train-only TruncatedSVD "
        f"({config.svd_n_components} components)...",
        config.verbose,
    )
    start = time.perf_counter()
    x_train_svd = svd.fit_transform(x_train_lexical)
    x_test_svd = svd.transform(x_test_lexical)
    svd_seconds = float(time.perf_counter() - start)

    x_train_svd = np.asarray(x_train_svd, dtype=np.float32)
    x_test_svd = np.asarray(x_test_svd, dtype=np.float32)
    explained_variance = float(np.sum(svd.explained_variance_ratio_))

    _log(
        f"{label} | TruncatedSVD done in {_format_seconds(svd_seconds)} "
        f"(explained variance ratio sum={explained_variance:.4f}).",
        config.verbose,
    )
    return x_train_svd, x_test_svd, svd_seconds, explained_variance


def _get_static_matrix(
    static_lookup: pd.DataFrame,
    source_ids: pd.Series,
    config: Exp1Config,
) -> np.ndarray:
    """Fetch cached static features in exactly the requested source-ID order."""
    matrix = static_lookup.loc[
        pd.Index(source_ids),
        FEATURE_COLUMNS,
    ].to_numpy(dtype=np.float32, copy=True)

    if matrix.shape[1] != len(FEATURE_COLUMNS):
        raise RuntimeError("Static feature matrix has an unexpected column count.")
    if not np.isfinite(matrix).all():
        raise RuntimeError("Static feature matrix contains NaN or infinite values.")
    return matrix



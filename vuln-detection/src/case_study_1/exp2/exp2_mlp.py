"""
CS1-EXP2-MLP: train-only TF-IDF + TruncatedSVD + static features + shallow MLP.

    normalized C/C++ function text
        -> word + character TF-IDF -> TruncatedSVD (dense)
        -> concat with 54 deterministic static features
        -> StandardScaler
        -> shallow MLP (hidden_dim_1 -> hidden_dim_2 -> 1 logit)

Evaluation protocol
--------------------
5-fold project-grouped, stratified CV; every fold takes a turn as the test
set (no separate fixed holdout). For each outer fold, hyperparameters are
selected via 3-fold inner CV on that outer fold's training projects only,
in two stages to keep the search tractable (a full joint grid would need
thousands of TruncatedSVD refits):

  Stage A (representation): word/char TF-IDF capacity (max_features, min_df)
  and svd_n_components, with the MLP architecture held at its default.
  Stage B (architecture): hidden_dim_1, hidden_dim_2, learning_rate, reusing
  Stage A's winning TF-IDF+SVD representation (already computed per inner
  fold, so Stage B needs no further vectorizer/SVD refitting).

The decision threshold is then selected (F1-maximizing grid) from the
winning configuration's pooled inner-validation scores. The winning
configuration is refit on the full outer-training partition (using one
project-disjoint split for early stopping) and scored once on the outer
test fold. Reported metrics are mean +/- std across the 5 outer folds.
"""


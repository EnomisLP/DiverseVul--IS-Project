@dataclass(frozen=True)
class Exp2Config:
    """Declared reproducible configuration for CS1-EXP2-MLP, including every searched grid."""

    experiment_name: str = "cs1_exp2_mlp"
    code_column: str = "normalized_code"
    source_id_column: str = "source_row_id"
    label_column: str = "label"
    project_column: str = "project"
    fold_column: str = "fold"

    n_splits: int = 5
    random_state: int = 42

    # Same lexical representation grid as EXP-1.
    word_ngram_range: tuple[int, int] = (1, 3)
    word_max_df: float = 0.995
    word_max_features_grid: tuple[int, ...] = (20_000, 50_000, 80_000)
    word_min_df_grid: tuple[int, ...] = (2, 3)

    char_analyzer: str = "char"
    char_ngram_range: tuple[int, int] = (3, 4)
    char_max_df: float = 0.995
    char_max_features_grid: tuple[int, ...] = (30_000, 60_000, 90_000)
    char_min_df_grid: tuple[int, ...] = (5, 8)

    lowercase: bool = False
    sublinear_tf: bool = True
    tfidf_norm: str = "l2"

    # TruncatedSVD is fitted only on inner-fold training data.
    svd_algorithm: str = "randomized"
    svd_n_iter: int = 5
    svd_n_oversamples: int = 10
    svd_n_components_grid: tuple[int, ...] = (128, 256, 384)

    # Stage B architecture search.
    hidden_dim_1_grid: tuple[int, ...] = (64, 128, 256)
    hidden_dim_2_grid: tuple[int, ...] = (32, 64, 128)
    learning_rate_grid: tuple[float, ...] = (1e-3, 5e-4, 1e-4)

    # Fixed default architecture used while Stage A searches representation.
    default_hidden_dim_1: int = 128
    default_hidden_dim_2: int = 64
    default_learning_rate: float = 1e-3

    max_epochs: int = 15
    early_stopping_patience: int = 3
    early_stopping_min_delta: float = 1e-4
    batch_size_gpu: int = 2_048
    batch_size_cpu: int = 1_024
    weight_decay: float = 1e-4
    use_pos_weight: bool = True

    inner_n_splits: int = 3
    inner_random_state: int = 20260707
    selection_metric: str = "average_precision_pr_auc"

    device: str = "auto"
    dataloader_num_workers: int = 0
    verbose: bool = True



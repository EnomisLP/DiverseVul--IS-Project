class ShallowMLP(nn.Module):
    """Feed-forward binary classifier returning logits."""

    def __init__(self, input_dim: int, hidden_dim_1: int, hidden_dim_2: int):
        """Build the hidden_dim_1 -> hidden_dim_2 -> 1 feed-forward network."""
        super().__init__()
        self.network = nn.Sequential(
            nn.Linear(input_dim, hidden_dim_1),
            nn.ReLU(),
            nn.Linear(hidden_dim_1, hidden_dim_2),
            nn.ReLU(),
            nn.Linear(hidden_dim_2, 1),
        )

    def forward(self, features: Tensor) -> Tensor:
        """Return logits for a batch of dense features."""
        return self.network(features).squeeze(dim=1)


